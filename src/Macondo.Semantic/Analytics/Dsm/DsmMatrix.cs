using Macondo.Semantic.Model;

namespace Macondo.Semantic.Analytics.Dsm;

/// <summary>
/// Represents the type or nature of a dependency between two containers or modules in a DSM.
/// </summary>
[Flags]
public enum DsmDependencyKind
{
    None = 0,
    Call = 1 << 0,
    Instantiation = 1 << 1,
    TypeUsage = 1 << 2,
    InheritanceOrImplements = 1 << 3,
    FieldAccess = 1 << 4,
    EventHandling = 1 << 5
}

/// <summary>
/// Single dependency detail between two symbols (caller -> called or user -> type).
/// </summary>
public sealed record DsmDependencyDetail(
    Guid SourceSymbolId,
    string SourceSymbolName,
    Guid TargetSymbolId,
    string TargetSymbolName,
    RelationshipKind RelationshipKind,
    string? Description = null
);

/// <summary>
/// DSM matrix cell at the intersection of a row (Source) and a column (Target).
/// </summary>
public sealed class DsmCell
{
    public int RowIndex { get; set; }
    public int ColumnIndex { get; set; }
    public Guid RowContainerId { get; init; }
    public Guid ColumnContainerId { get; init; }
    
    /// <summary>Total number of links/dependencies between the row module and the column module.</summary>
    public int Weight { get; set; }

    /// <summary>Types of dependencies present.</summary>
    public DsmDependencyKind DependencyKinds { get; set; } = DsmDependencyKind.None;

    /// <summary>Indicates whether this cell is part of a mutual/circular dependency loop.</summary>
    public bool IsInCycle { get; set; }

    /// <summary>List of specific links (for click inspection).</summary>
    public List<DsmDependencyDetail> Details { get; } = new();

    public bool HasDependency => Weight > 0;
}

/// <summary>
/// DSM matrix row or column representing a module/class/file.
/// </summary>
public sealed class DsmItem
{
    public int Index { get; set; }
    public Guid Id { get; init; }
    public string Name { get; init; } = string.Empty;
    public string QualifiedName { get; init; } = string.Empty;
    public SymbolKind Kind { get; init; }
    public int ClusterId { get; set; }
    public int InDegree { get; set; }
    public int OutDegree { get; set; }
    public bool HasCircularDependencies { get; set; }
}

/// <summary>
/// Complete model of the DSM matrix generated by a CodeGraph.
/// </summary>
public sealed class DsmMatrix
{
    public List<DsmItem> Items { get; init; } = new();
    public DsmCell[,] Cells { get; internal set; } = new DsmCell[0, 0];
    public List<List<Guid>> StronglyConnectedComponents { get; init; } = new();
    public int TotalDependencies { get; set; }
    public int TotalCyclicDependencies { get; set; }

    public int Size => Items.Count;

    public DsmCell GetCell(int row, int col) => Cells[row, col];

    public void InitializeCells()
    {
        int n = Items.Count;
        Cells = new DsmCell[n, n];
        for (int r = 0; r < n; r++)
        {
            for (int c = 0; c < n; c++)
            {
                Cells[r, c] = new DsmCell
                {
                    RowIndex = r,
                    ColumnIndex = c,
                    RowContainerId = Items[r].Id,
                    ColumnContainerId = Items[c].Id
                };
            }
        }
    }
}

/// <summary>
/// DSM matrix sorting mode.
/// </summary>
public enum DsmOrdering
{
    Alphabetical,
    ByKindAndName,
    TopologicalOrPartitioned
}
