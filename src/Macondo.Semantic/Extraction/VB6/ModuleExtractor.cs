using Antlr4.Runtime;
using Macondo.Parser.Diagnostics;
using Macondo.Parser.Grammar;
using Macondo.Semantic.Model;

namespace Macondo.Semantic.Extraction;

/// <summary>
/// Represents the result of the semantic extraction of a single VB6 module or file.
/// Contains the created root symbol, any syntax errors detected by ANTLR,
/// the list of Subs that appear to be event handlers and the parsing tree for subsequent passes.
/// </summary>
public sealed class ModuleExtractionResult
{
    /// <summary>Symbol of the generated module (of type Class, Form, Module or UserControl).</summary>
    public required Symbol ModuleSymbol { get; init; }

    /// <summary>List of syntax errors detected by ANTLR lexers and parsers.</summary>
    public required IReadOnlyList<string> ParseErrors { get; init; }

    /// <summary>Sub procedure names that match the event handler convention.</summary>
    public required IReadOnlyList<string> LikelyEventHandlerNames { get; init; }

    /// <summary>List of interfaces implemented by the module via the 'Implements' clause.</summary>
    public IReadOnlyList<(string InterfaceName, int Line)> ImplementedInterfaces { get; init; } = Array.Empty<(string, int)>();

    /// <summary>
    /// Parse tree generated by ANTLR (<see cref="VisualBasic6Parser.StartRuleContext"/>).
    /// Kept in memory temporarily to allow subsequent analyzers (e.g. <see cref="Macondo.Semantic.Resolution.RoutineInvocationAnalyzer"/>)
    /// to traverse method bodies without having to reparse the source file from scratch.
    /// It is released (set to null) when the Call Graph construction is finished to minimize the memory footprint.
    /// </summary>
    public VisualBasic6Parser.StartRuleContext? ParseTree { get; set; }

    /// <summary>Indicates whether the module was parsed and extracted without syntax errors.</summary>
    public bool Success => ParseErrors.Count == 0;
}

/// <summary>
/// Facade and entry point for parsing and semantic extraction of a single VB6 source file.
/// 
/// EXECUTION FLOW:
/// 1. Determine the form type from the extension (.cls -> Class, .frm -> Form, .bas -> Module, .ctl -> UserControl).
/// 2. Creates the root <see cref="Symbol"/> of the form and registers it in the shared <see cref="CodeGraph"/>.
/// 3. Perform lexing and parsing with ANTLR4 (<see cref="VisualBasic6Lexer"/>, <see cref="VisualBasic6Parser"/>)
/// catching any errors via <see cref="CollectingErrorListener"/>.
/// 4. Run <see cref="SymbolExtractor"/> on the parse tree to extract all internal symbols
/// and building CONTAINS relationships.
/// 5. Returns the structured result in <see cref="ModuleExtractionResult"/>.
/// </summary>
public static class ModuleExtractor
{
    /// <summary>
    /// Performs parsing and extraction of symbols for a VB6 source file, inserting them into the in-place graph.
    /// </summary>
    /// <param name="graph">The graph in memory in which to aggregate the symbols.</param>
    /// <param name="filePath">File path or name (used for extension and module name).</param>
    /// <param name="sourceText">The complete VB6 source code of the module.</param>
    /// <returns>The result of the extraction with the symbols and the parsing tree.</returns>
    public static ModuleExtractionResult ExtractModule(CodeGraph graph, string filePath, string sourceText)
    {
        // 1. Identify the module type by the file extension (.cls, .frm, .bas, .ctl)
        var moduleKind = ModuleFileKind.FromExtension(filePath);
        var moduleName = Path.GetFileNameWithoutExtension(filePath);

        // 2. Create the root container symbol for the form
        var moduleSymbol = new Symbol
        {
            Id = Guid.NewGuid(),
            Kind = moduleKind,
            Name = moduleName,
            QualifiedName = moduleName,
            FilePath = filePath,
            Language = SourceLanguage.VisualBasic6,
            LineStart = 1,
            LineEnd = 1
        };
        graph.Symbols.Add(moduleSymbol);

        var errors = new List<string>();

        // 3. Configura Lexer ANTLR
        var lexer = new VisualBasic6Lexer(new AntlrInputStream(sourceText));
        lexer.RemoveErrorListeners();
        lexer.AddErrorListener(new CollectingErrorListener(errors));

        // 4. Configura TokenStream e Parser ANTLR
        var parser = new VisualBasic6Parser(new CommonTokenStream(lexer));
        parser.RemoveErrorListeners();
        parser.AddErrorListener(new CollectingErrorListener(errors));

        // 5. Start parsing from main rule 'startRule'
        var tree = parser.startRule();

        // Updates the final line of the form based on the latest token in the tree if available
        if (tree?.Stop?.Line is int stopLine and > 0)

            moduleSymbol.LineEnd = stopLine;

        // 6. Run the SymbolExtractor on the parse tree to extract routines, properties, variables, constants, etc.
        // Resilient execution (best-effort): still extracts all valid symbols from the parse tree too
        // in the presence of syntax errors on individual instructions.
        var likelyEventHandlers = Array.Empty<string>();
        var implementedInterfaces = Array.Empty<(string, int)>();
        if (tree != null)
        {
            var extractor = new SymbolExtractor(graph, moduleSymbol, filePath);
            extractor.Visit(tree);
            likelyEventHandlers = extractor.LikelyEventHandlerNames.ToArray();
            implementedInterfaces = extractor.ImplementedInterfaces.ToArray();
        }

        return new ModuleExtractionResult
        {
            ModuleSymbol = moduleSymbol,
            ParseErrors = errors,
            LikelyEventHandlerNames = likelyEventHandlers,
            ImplementedInterfaces = implementedInterfaces,
            ParseTree = tree
        };
    }
}
