using FluentAssertions;
using Macondo.App.Generation;
using Macondo.Semantic.Model;
using Xunit;

namespace Macondo.Tests.Common.App;

public class FakeGraphGeneratorTests
{
    /// <summary>
    /// Verify that FakeGraphGenerator generates a valid synthetic VisualCodeGraph with the number
    /// expected of container nodes, method nodes and relational links.
    /// </summary>
    [Fact]
    public void FakeGraphGenerator_ShouldGenerateRequestedStructure()
    {
        // Arrange & Act
        var visualGraph = FakeGraphGenerator.Generate(seed: 123, containerCount: 10, methodsPerContainer: 5);

        // Assert
        visualGraph.Should().NotBeNull();
        visualGraph.Nodes.Should().NotBeEmpty();
        visualGraph.Edges.Should().NotBeEmpty();

        // 1 Project root node + 10 containers + methods
        var projectNode = visualGraph.Nodes.FirstOrDefault(n => n.Kind == SymbolKind.Project);
        projectNode.Should().NotBeNull();

        var containerNodes = visualGraph.Nodes.Where(n => n.Kind is SymbolKind.Class or SymbolKind.Form or SymbolKind.Module).ToList();
        containerNodes.Should().HaveCount(10);

        var methodNodes = visualGraph.Nodes.Where(n => n.Kind is SymbolKind.Method or SymbolKind.Property).ToList();
        methodNodes.Should().NotBeEmpty();
    }

    /// <summary>
    /// Verify that all nodes generated by the FakeGraphGenerator have valid spatial coordinates (not NaN, not Infinite)
    /// and that the calling and containment relationships are consistent.
    /// </summary>
    [Fact]
    public void FakeGraphGenerator_ShouldAssignValidCoordinatesAndEdges()
    {
        // Arrange & Act
        var visualGraph = FakeGraphGenerator.Generate(seed: 42, containerCount: 5, methodsPerContainer: 4);

        // Assert
        foreach (var node in visualGraph.Nodes)
        {
            node.X.Should().NotBe(double.NaN);
            node.Y.Should().NotBe(double.NaN);
            double.IsInfinity(node.X).Should().BeFalse();
            double.IsInfinity(node.Y).Should().BeFalse();
            node.Name.Should().NotBeNullOrWhiteSpace();
            node.QualifiedName.Should().NotBeNullOrWhiteSpace();
        }

        // All edges must point to existing nodes in the graph
        var nodeIds = visualGraph.Nodes.Select(n => n.Id).ToHashSet();
        foreach (var edge in visualGraph.Edges)
        {
            nodeIds.Should().Contain(edge.SourceId);
            nodeIds.Should().Contain(edge.TargetId);
        }
    }

    /// <summary>
    /// Verify that the default generation produces exactly 5000 nodes and that the distribution
    /// of the members between the components is heterogeneous (components with many nodes and components with few nodes).
    /// </summary>
    [Fact]
    public void FakeGraphGenerator_DefaultCall_ShouldGenerate5000NodesWithHeterogeneousComponents()
    {
        // Arrange & Act
        var visualGraph = FakeGraphGenerator.Generate(seed: 42);

        // Assert
        visualGraph.Should().NotBeNull();
        visualGraph.Nodes.Should().HaveCount(5000);

        var containers = visualGraph.Nodes.Where(n => n.IsContainer).ToList();
        containers.Should().HaveCountGreaterThan(50);

        var memberCounts = containers.Select(c => visualGraph.GetChildren(c.Id).Count()).ToList();
        // Strong heterogeneity: presence of leader components with many methods and small/leaf components with very few methods
        memberCounts.Max().Should().BeGreaterThan(60);
        memberCounts.Min().Should().BeLessThanOrEqualTo(3);

        // Check that all nodes have finite coordinates and not NaNs
        foreach (var node in visualGraph.Nodes)
        {
            node.X.Should().NotBe(double.NaN);
            node.Y.Should().NotBe(double.NaN);
            double.IsInfinity(node.X).Should().BeFalse();
            double.IsInfinity(node.Y).Should().BeFalse();
        }
    }
}
